// Bundles api/src/edge_app.js into a single Supabase Edge Function and writes the prefixed SQL migration.
// Usage: node scripts/build-edge.js
const fs = require('fs');
const path = require('path');
const esbuild = require('esbuild');

const root = path.join(__dirname, '..');
const EXT = {
  express: ['default', 'npm:express@4.21.2'],
  cors: ['default', 'npm:cors@2.8.5'],
  'express-rate-limit': ['default', 'npm:express-rate-limit@7.5.0'],
  ethers: ['star', 'npm:ethers@6.13.4'],
  '@supabase/supabase-js': ['star', 'npm:@supabase/supabase-js@2.45.4'],
  crypto: ['star', 'node:crypto'],
};

const plugin = {
  name: 'edge',
  setup(b) {
    b.onResolve({ filter: /^(npm|node):/ }, (a) => ({ path: a.path, external: true }));
    b.onResolve({ filter: /^dotenv$/ }, () => ({ path: 'dotenv', namespace: 'stub' }));
    b.onLoad({ filter: /.*/, namespace: 'stub' }, () => ({ contents: 'module.exports = { config() {} };', loader: 'js' }));
    b.onResolve({ filter: /^[^./]/ }, (a) => (EXT[a.path] ? { path: a.path, namespace: 'ext' } : undefined));
    b.onLoad({ filter: /.*/, namespace: 'ext' }, (a) => {
      const [kind, spec] = EXT[a.path];
      return {
        contents: kind === 'default' ? `import m from '${spec}'; module.exports = m;` : `import * as m from '${spec}'; module.exports = m;`,
        loader: 'js',
      };
    });
    // the Edge build always uses the Supabase-only adapter
    b.onResolve({ filter: /^\.\/db$/ }, (a) => ({ path: path.join(root, 'api/src/db.edge.js') }));
  },
};

(async () => {
  const entry = path.join(root, 'api/src/edge_app.js');
  const res = await esbuild.build({
    entryPoints: [entry], bundle: true, write: false, format: 'esm', platform: 'node', target: 'es2022',
    plugins: [plugin], legalComments: 'none', logLevel: 'warning',
  });
  const head = `// @ts-nocheck\n// Generated by scripts/build-edge.js, do not edit by hand.\nglobalThis.process ??= { env: Deno.env.toObject() };\n`;
  const out = path.join(root, 'supabase/functions/tickermind-api/index.ts');
  fs.writeFileSync(out, head + res.outputFiles[0].text);
  console.log('edge function:', out, (fs.statSync(out).size / 1024).toFixed(1) + ' KB');

  const tables = ['agents', 'tasks', 'reports', 'services', 'orders', 'a2a_requests', 'ledger_entries', 'positions'];
  let sql = fs.readFileSync(path.join(root, 'supabase/schema.sql'), 'utf8');
  for (const t of tables) sql = sql.replace(new RegExp(`\\b${t}\\b`, 'g'), 'tm_' + t);
  fs.writeFileSync(path.join(root, 'supabase/migrations/001_tickermind_tables.sql'), sql);
  console.log('migration written');
})();
